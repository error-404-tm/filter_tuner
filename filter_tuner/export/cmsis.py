"""CMSIS-DSP biquad cascade coefficient export (C source text).

CMSIS writes the recursion as
    y[n] = b0 x[n] + b1 x[n-1] + b2 x[n-2] + a1 y[n-1] + a2 y[n-2]
so its a1/a2 are the *negated* scipy/MATLAB denominator coefficients.
"""

from __future__ import annotations

import numpy as np


def _header(name: str, sos: np.ndarray, kind: str) -> str:
    return (
        f"/* {name}: {len(sos)}-stage biquad cascade ({kind})\n"
        f" * Generated by filter_tuner. Coefficient order per stage is the\n"
        f" * CMSIS-DSP order; feedback terms are negated relative to scipy. */\n"
    )


def _rows(values, fmt) -> str:
    return ",\n".join("    " + ", ".join(fmt(v) for v in row) for row in values)


def f32_df2t(sos: np.ndarray, name: str = "filt") -> str:
    sos = np.asarray(sos, dtype=float)
    rows = [[s[0], s[1], s[2], -s[4], -s[5]] for s in sos]
    n = len(sos)
    return (
        _header(name, sos, "arm_biquad_cascade_df2T_f32")
        + "#include \"arm_math.h\"\n\n"
        + f"#define {name.upper()}_NUM_STAGES {n}\n\n"
        + f"static const float32_t {name}_coeffs[5 * {n}] = {{\n"
        + "    /* b0, b1, b2, a1, a2 */\n"
        + _rows(rows, lambda v: f"{v:.9e}f")
        + "\n};\n\n"
        + f"static float32_t {name}_state[2 * {n}];\n"
        + f"static arm_biquad_cascade_df2T_instance_f32 {name}_inst;\n\n"
        + f"void {name}_init(void)\n{{\n"
        + f"    arm_biquad_cascade_df2T_init_f32(&{name}_inst, {name.upper()}_NUM_STAGES,\n"
        + f"                                     {name}_coeffs, {name}_state);\n}}\n\n"
        + f"/* arm_biquad_cascade_df2T_f32(&{name}_inst, src, dst, block_size); */\n"
    )


def post_shift(sos: np.ndarray) -> int:
    m = float(np.max(np.abs(np.asarray(sos)[:, [0, 1, 2, 4, 5]])))
    return max(0, int(np.floor(np.log2(m))) + 1) if m > 0 else 0


def _fixed(values, frac: int, bits: int):
    q = np.round(np.asarray(values) * (1 << frac)).astype(np.int64)
    lo, hi = -(1 << (bits - 1)), (1 << (bits - 1)) - 1
    return np.clip(q, lo, hi)


def q31_df1(sos: np.ndarray, name: str = "filt") -> str:
    sos = np.asarray(sos, dtype=float)
    ps = post_shift(sos)
    rows = np.array([[s[0], s[1], s[2], -s[4], -s[5]] for s in sos]) / (1 << ps)
    ints = _fixed(rows, 31, 32)
    n = len(sos)
    return (
        _header(name, sos, "arm_biquad_cascade_df1_q31")
        + "#include \"arm_math.h\"\n\n"
        + f"#define {name.upper()}_NUM_STAGES {n}\n"
        + f"#define {name.upper()}_POST_SHIFT {ps}  /* coefficients stored as c / 2^{ps} */\n\n"
        + f"static const q31_t {name}_coeffs[5 * {n}] = {{\n"
        + "    /* b0, b1, b2, a1, a2 (Q31) */\n"
        + _rows(ints, lambda v: f"{int(v)}")
        + "\n};\n\n"
        + f"static q31_t {name}_state[4 * {n}];\n"
        + f"static arm_biquad_casd_df1_inst_q31 {name}_inst;\n\n"
        + f"void {name}_init(void)\n{{\n"
        + f"    arm_biquad_cascade_df1_init_q31(&{name}_inst, {name.upper()}_NUM_STAGES,\n"
        + f"                                    {name}_coeffs, {name}_state,\n"
        + f"                                    {name.upper()}_POST_SHIFT);\n}}\n"
    )


def q15_df1(sos: np.ndarray, name: str = "filt") -> str:
    sos = np.asarray(sos, dtype=float)
    ps = post_shift(sos)
    rows = np.array([[s[0], s[1], s[2], -s[4], -s[5]] for s in sos]) / (1 << ps)
    ints = _fixed(rows, 15, 16)
    # q15 layout has a padding zero after b0: {b0, 0, b1, b2, a1, a2}
    ints = np.insert(ints, 1, 0, axis=1)
    n = len(sos)
    return (
        _header(name, sos, "arm_biquad_cascade_df1_q15")
        + "#include \"arm_math.h\"\n\n"
        + f"#define {name.upper()}_NUM_STAGES {n}\n"
        + f"#define {name.upper()}_POST_SHIFT {ps}\n\n"
        + f"static const q15_t {name}_coeffs[6 * {n}] = {{\n"
        + "    /* b0, 0, b1, b2, a1, a2 (Q15) */\n"
        + _rows(ints, lambda v: f"{int(v)}")
        + "\n};\n\n"
        + f"static q15_t {name}_state[4 * {n}];\n"
        + f"static arm_biquad_casd_df1_inst_q15 {name}_inst;\n\n"
        + f"void {name}_init(void)\n{{\n"
        + f"    arm_biquad_cascade_df1_init_q15(&{name}_inst, {name.upper()}_NUM_STAGES,\n"
        + f"                                    {name}_coeffs, {name}_state,\n"
        + f"                                    {name.upper()}_POST_SHIFT);\n}}\n"
    )


FORMATS = {
    "CMSIS f32 (DF2T)": f32_df2t,
    "CMSIS q31 (DF1)": q31_df1,
    "CMSIS q15 (DF1)": q15_df1,
}
